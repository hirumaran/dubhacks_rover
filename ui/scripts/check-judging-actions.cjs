const path = require("node:path");
const assert = require("node:assert/strict");
module.exports = async (page, base) => {
  const button = (name) => page.getByRole("button", { name, exact: true });
  await page.goto(`${base}/map`);
  await page.getByText("Your search areas.", { exact: true }).waitFor();
  await page.getByText("PRIVATE TO YOUR ACCOUNT", { exact: true }).waitFor();
  assert.equal(await page.locator('a[href*="openstreetmap"]').count(), 0);
  await button("View my search activity").click();
  await page.getByText("Your activity.", { exact: true }).waitFor();

  await page.goto(`${base}/item/10000000-0000-0000-0000-000000000004`);
  await button("This might be mine").click();
  await page.getByLabel("Distinguishing features").fill("Judging test: my engraved key ring");
  await page.getByLabel("Where and when did you lose it?").fill("Yesterday on campus");
  await button("Submit ownership claim").click();
  await page.getByText("Claim submitted", { exact: true }).waitFor();
  await button("View claims").click();
  await page.getByText("My claims", { exact: true }).waitFor();
  await page.getByText("pending", { exact: true }).first().waitFor();
  await page.getByText("Private evidence: Judging test: my engraved key ring", { exact: true }).waitFor();

  await page.goto(`${base}/item/10000000-0000-0000-0000-000000000004`);
  await button("Save item").click();
  await button("Remove from saved").waitFor();
  await button("Report incorrect information").click();
  await page.getByLabel("What needs correcting?").fill("Judging test correction; please disregard.");
  await button("Send for review").click();
  await page.getByText("Thanks for looking out", { exact: true }).waitFor();
  await button("OK").click();
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await button("Share listing").click();
  await page.getByText("Share this item", { exact: true }).waitFor();
  await button("Done").click();

  await page.goto(`${base}/profile`);
  await page.getByLabel("Display name", { exact: true }).fill("Judge action check");
  await button("Save profile").click();
  await page.getByText("Judge action check", { exact: true }).waitFor();
  const chooser = page.waitForEvent("filechooser");
  await button("Change profile photo").click();
  await (await chooser).setFiles(path.resolve(__dirname, "../assets/demo/card-holder.jpg"));
  await page.locator('img[src*="avatars"]').waitFor();
  await button("Saved Items").click();
  await page.getByText("Saved items", { exact: true }).waitFor();
  await page.getByRole("button", { name: "View A set of keys", exact: true }).waitFor();
  await page.goto(`${base}/profile`);
  await button("Search History").click();
  await page.getByText("Search history", { exact: true }).waitFor();
  await page.getByText(/^(assigned|queued)$/).first().waitFor();
  await page.goto(`${base}/profile`);
  await button("Sign out").click();
  await page.getByText("Sign out?", { exact: true }).waitFor();
  await button("Cancel").click();
  await button("Help & Support").click();
  await page.getByText("A little help, Husky.", { exact: true }).waitFor();
  await page.goto(`${base}/profile`);
  await button("Privacy & Security").click();
  await button("Delete my account and data").click();
  await button("Cancel").click();
  await button("Delete my account and data").click();
  await button("Delete account").click();
  await button("Explore Demo").waitFor({ timeout: 60000 });
  console.log("Hosted buttons: private areas, claims, corrections, sharing, profile/photo, saved/search collections, sign-out confirmation, help, and account/photo deletion passed.");
};
